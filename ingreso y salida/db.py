def consultar_salida_personal(
    documento: str, fecha_actual: str
) -> dict[str, object] | None:
    with db_connection() as connection:
        fila = connection.execute(
            """
            SELECT e.documento, e.nombre, e.area,
                   s.id AS movimiento_id, s.salida, s.motivo, s.destino,
                   COALESCE(s.no_regresa, 0) AS no_regresa,
                   e.cargo
            FROM empleados e
            LEFT JOIN salidas_personal s
              ON s.documento_empleado = e.documento
             AND s.regreso IS NULL
             AND s.no_regresa = 0
            WHERE e.documento = %s AND e.activo = 1
            """,
            (documento,),
        ).fetchone()
        if fila is None:
            return None
        resultado = dict(fila)
        if resultado["movimiento_id"] is None:
            no_regreso = connection.execute(
                """
                SELECT id AS movimiento_id, salida, motivo, destino, no_regresa
                FROM salidas_personal
                WHERE documento_empleado = %s AND no_regresa = 1
                  AND regreso IS NULL
                  AND SUBSTRING(salida FROM 1 FOR 10) = %s
                ORDER BY salida DESC
                LIMIT 1
                """,
                (documento, fecha_actual),
            ).fetchone()
            if no_regreso is not None:
                resultado.update(dict(no_regreso))
    return resultado


def registrar_salida_personal(
    documento: str,
    salida: str,
    motivo: str,
    destino: str,
    firma: bytes,
    no_regresa: bool,
) -> str:
    with db_connection() as connection:
        empleado = connection.execute(
            "SELECT activo FROM empleados WHERE documento = %s FOR UPDATE",
            (documento,),
        ).fetchone()
        if empleado is None or not empleado["activo"]:
            return "no_disponible"

        abierta = connection.execute(
            """
            SELECT 1 FROM salidas_personal
            WHERE documento_empleado = %s AND regreso IS NULL AND no_regresa = 0
            """,
            (documento,),
        ).fetchone()
        if abierta is not None:
            return "salida_abierta"
        si_no_regresa = connection.execute(
            """
            SELECT 1 FROM salidas_personal
            WHERE documento_empleado = %s AND no_regresa = 1
              AND regreso IS NULL
              AND SUBSTRING(salida FROM 1 FOR 10) =
                  SUBSTRING(%s FROM 1 FOR 10)
            LIMIT 1
            """,
            (documento, salida),
        ).fetchone()
        if si_no_regresa is not None:
            return "ya_indico_no_regreso"

        connection.execute(
            """
            INSERT INTO salidas_personal
                (documento_empleado, salida, motivo, destino, firma, no_regresa)
            VALUES (%s, %s, %s, %s, %s, %s)
            """,
            (documento, salida, motivo, destino, firma, int(no_regresa)),
        )
    return "no_regresa" if no_regresa else "salida"


def registrar_regreso_personal(documento: str, regreso: str) -> bool:
    with db_connection() as connection:
        cursor = connection.execute(
            """
            UPDATE salidas_personal
            SET regreso = %s
            WHERE id = (
                SELECT id FROM salidas_personal
                WHERE documento_empleado = %s AND regreso IS NULL
                  AND (
                      no_regresa = 0
                      OR (
                          no_regresa = 1
                          AND SUBSTRING(salida FROM 1 FOR 10) =
                              SUBSTRING(%s FROM 1 FOR 10)
                      )
                  )
                ORDER BY salida DESC
                LIMIT 1
            )
            AND regreso IS NULL
            """,
            (regreso, documento, regreso),
        )
    return cursor.rowcount == 1


