import os
from contextlib import contextmanager
from pathlib import Path
from typing import Iterator

import psycopg
from dotenv import load_dotenv
from psycopg.rows import dict_row

load_dotenv()

INSTANCE_DIR = Path(__file__).resolve().parent / "instance"
SQLITE_SOURCE_PATH = Path(
    os.environ.get(
        "INGRESOS_SQLITE_PATH", INSTANCE_DIR / "ingresos_personal.db"
    )
)
DATABASE_URL = os.environ.get("INGRESOS_DATABASE_URL") or os.environ.get(
    "DATABASE_URL"
)


@contextmanager
def db_connection() -> Iterator[psycopg.Connection]:
    if not DATABASE_URL:
        raise RuntimeError(
            "Configure INGRESOS_DATABASE_URL en el archivo .env para conectar "
            "la aplicación a PostgreSQL."
        )

    connection = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=5)
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def init_db() -> None:
    statements = (
        """
        CREATE TABLE IF NOT EXISTS empleados (
            documento TEXT PRIMARY KEY,
            nombre TEXT NOT NULL,
            area TEXT NOT NULL,
            cargo TEXT NOT NULL,
            activo SMALLINT NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
            creado_en TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS cuentas_admin (
            usuario TEXT PRIMARY KEY,
            password_hash TEXT NOT NULL,
            creado_en TEXT NOT NULL,
            rol TEXT NOT NULL DEFAULT 'admin'
                CHECK (rol IN ('admin', 'lectura'))
        )
        """,
        """
        ALTER TABLE cuentas_admin
            ADD COLUMN IF NOT EXISTS rol TEXT NOT NULL DEFAULT 'admin'
                CHECK (rol IN ('admin', 'lectura'))
        """,
        """
        CREATE TABLE IF NOT EXISTS salidas_personal (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            documento_empleado TEXT NOT NULL REFERENCES empleados(documento),
            salida TEXT NOT NULL,
            regreso TEXT,
            motivo TEXT NOT NULL,
            destino TEXT NOT NULL,
            firma BYTEA,
            no_regresa SMALLINT NOT NULL DEFAULT 0
                CHECK (no_regresa IN (0, 1))
        )
        """,
        """
        CREATE UNIQUE INDEX IF NOT EXISTS idx_salidas_personal_abiertas
            ON salidas_personal(documento_empleado)
            WHERE regreso IS NULL AND no_regresa = 0
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_salidas_personal_fecha
            ON salidas_personal(salida DESC)
        """,
        """
        ALTER TABLE salidas_personal
            ADD COLUMN IF NOT EXISTS firma BYTEA
        """,
        """
        ALTER TABLE salidas_personal
            ADD COLUMN IF NOT EXISTS regreso_confirmado BOOLEAN NOT NULL DEFAULT TRUE
        """,
        """
        ALTER TABLE salidas_personal
            ADD COLUMN IF NOT EXISTS regreso_regularizado BOOLEAN NOT NULL DEFAULT FALSE
        """,
        """
        ALTER TABLE salidas_personal
            ADD COLUMN IF NOT EXISTS regreso_regularizado_por TEXT
        """,
        """
        ALTER TABLE salidas_personal
            ADD COLUMN IF NOT EXISTS regreso_regularizado_en TEXT
        """,
        """
        ALTER TABLE salidas_personal
            ADD COLUMN IF NOT EXISTS regreso_regularizado_motivo TEXT
        """,
        """
        ALTER TABLE salidas_personal
            ADD COLUMN IF NOT EXISTS regreso_regularizado_evidencia TEXT
        """,
    )
    with db_connection() as connection:
        for statement in statements:
            connection.execute(statement)


def existe_cuenta_admin() -> bool:
    with db_connection() as connection:
        return connection.execute(
            "SELECT 1 FROM cuentas_admin LIMIT 1"
        ).fetchone() is not None


def obtener_cuenta_admin(usuario: str) -> dict[str, object] | None:
    with db_connection() as connection:
        return connection.execute(
            "SELECT usuario, password_hash, rol FROM cuentas_admin WHERE usuario = %s",
            (usuario,),
        ).fetchone()


def crear_cuenta_admin(usuario: str, password_hash: str, creado_en: str) -> bool:
    with db_connection() as connection:
        if connection.execute(
            "SELECT 1 FROM cuentas_admin LIMIT 1"
        ).fetchone():
            return False
        connection.execute(
            """
            INSERT INTO cuentas_admin (usuario, password_hash, creado_en)
            VALUES (%s, %s, %s)
            """,
            (usuario, password_hash, creado_en),
        )
    return True


