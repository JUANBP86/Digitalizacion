def regularizar_regreso_personal(
    movimiento_id: int,
    regreso: str,
    regreso_confirmado: bool,
    admin: str,
    regularizado_en: str,
    motivo: str,
    evidencia: str,
) -> bool:
    with db_connection() as connection:
        cursor = connection.execute(
            """
            UPDATE salidas_personal
            SET regreso = %s,
                regreso_confirmado = %s,
                regreso_regularizado = TRUE,
                regreso_regularizado_por = %s,
                regreso_regularizado_en = %s,
                regreso_regularizado_motivo = %s,
                regreso_regularizado_evidencia = %s
            WHERE id = %s AND regreso IS NULL AND no_regresa = 0
            """,
            (
                regreso,
                regreso_confirmado,
                admin,
                regularizado_en,
                motivo,
                evidencia,
                movimiento_id,
            ),
        )
    return cursor.rowcount == 1


def obtener_salidas_activas() -> list[dict[str, object]]:
    with db_connection() as connection:
        filas = connection.execute(
            """
            SELECT s.id AS movimiento_id, e.documento, e.nombre, e.area, e.cargo,
                   s.salida, s.motivo, s.destino
            FROM salidas_personal s
            JOIN empleados e ON e.documento = s.documento_empleado
            WHERE s.regreso IS NULL AND s.no_regresa = 0
            ORDER BY s.salida
            """
        ).fetchall()
    return [dict(fila) for fila in filas]


def obtener_historial_salidas() -> list[dict[str, object]]:
    with db_connection() as connection:
        filas = connection.execute(
            """
            SELECT s.id AS movimiento_id, e.documento, e.nombre, e.area, e.cargo,
                   s.salida, s.regreso, s.regreso_confirmado,
                   s.regreso_regularizado, s.regreso_regularizado_por,
                   s.regreso_regularizado_en, s.regreso_regularizado_motivo,
                   s.regreso_regularizado_evidencia,
                   s.motivo, s.destino, s.no_regresa,
                   CASE WHEN s.firma IS NOT NULL THEN 1 ELSE 0 END AS tiene_firma,
                   CASE
                       WHEN s.regreso IS NOT NULL AND NOT s.regreso_confirmado
                           THEN 'Cierre administrativo (hora no confirmada)'
                       WHEN s.regreso IS NOT NULL AND s.regreso_regularizado
                           THEN 'Regreso regularizado con hora confirmada'
                       WHEN s.regreso IS NOT NULL THEN 'Regresó'
                       WHEN s.no_regresa = 1 THEN 'No regresa en el turno'
                       ELSE 'Fuera de las instalaciones'
                   END AS estado
            FROM salidas_personal s
            JOIN empleados e ON e.documento = s.documento_empleado
            ORDER BY s.salida DESC, s.id DESC
            """
        ).fetchall()
    return [dict(fila) for fila in filas]


def obtener_reporte_dia(fecha: str) -> list[dict[str, object]]:
    with db_connection() as connection:
        filas = connection.execute(
            """
            SELECT e.documento, e.nombre, e.cargo, s.salida, s.regreso,
                   s.regreso_confirmado, s.regreso_regularizado,
                   s.regreso_regularizado_por, s.regreso_regularizado_en,
                   s.regreso_regularizado_motivo, s.regreso_regularizado_evidencia,
                   s.motivo, s.destino, s.firma, s.no_regresa
            FROM salidas_personal s
            JOIN empleados e ON e.documento = s.documento_empleado
            WHERE SUBSTRING(s.salida FROM 1 FOR 10) = %s
            ORDER BY s.salida, s.id
            """,
            (fecha,),
        ).fetchall()
    return [dict(fila) for fila in filas]


def obtener_firma_salida(movimiento_id: int) -> bytes | None:
    with db_connection() as connection:
        fila = connection.execute(
            "SELECT firma FROM salidas_personal WHERE id = %s",
            (movimiento_id,),
        ).fetchone()
    if fila is None or fila["firma"] is None:
        return None
    firma = fila["firma"]
    if isinstance(firma, memoryview):
        return firma.tobytes()
    return bytes(firma)
